/** 按朝代先后排序一条沿革轴（稳定排序，同代保持原序） */
// 跨代分期名 → 以其起始朝代为序（否则「隋唐」「汉唐」「宋元」会被排到末尾）
const ERA_ANCHOR = { 汉唐: '汉代', 隋唐: '隋代', 宋元: '宋代', 辽金: '辽代', 明清: '明代', 楚汉: '汉代', 秦汉: '秦代', 东周: '周代', 金元: '金代', 北宋: '宋代', 南宋: '宋代', 东汉: '汉代', 西汉: '汉代', 先秦: '周代' }

export function sortTimeline(timeline) {
  const rank = (e) => {
    const key = ERA_ANCHOR[e] || e
    const i = ERA_ORDER.indexOf(key)
    return i < 0 ? ERA_ORDER.length : i
  }
  return timeline.map((it, i) => ({ it, i })).sort((a, b) => rank(a.it[0]) - rank(b.it[0]) || a.i - b.i).map((x) => x.it)
}
