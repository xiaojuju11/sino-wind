// 生僻 / 海外城邑的典雅提示与推荐（用户输入尔湾、外埠等时给出）
export const NOT_FOUND_TIP = '虽身在万里瀛海，心系九州故里'
export const RECOMMEND_CITIES = ['苏州', '杭州', '扬州', '南京', '绍兴', '成都']

/** 查城邑演进轴；命中返回 { key, timeline }，未收录返回 null */
export function cityChronicle(name) {
  const key = String(name || '').trim()
  if (!key) return null
  if (CITY_CHRONICLE[key]) return { key, timeline: CITY_CHRONICLE[key] }
  // 允许「西安」「西安市」「长安」等写法：按包含关系兜底匹配
  const hit = Object.keys(CITY_CHRONICLE).find((k) => key === k || key.startsWith(k) || k.startsWith(key))
  return hit ? { key: hit, timeline: CITY_CHRONICLE[hit] } : null
}

/** 古典雅称：取演进轴中「汉唐/唐代」一段的城名作为该城最负盛名的古称 */
export function classicNameOf(name) {
  const c = cityChronicle(name)
  if (!c) return ''
  const preferred = c.timeline.find(([era]) => /汉唐|唐代|唐代/.test(era))
  return (preferred || c.timeline[c.timeline.length - 1])[1]
}
