const byCity = new Map()
for (const r of d) {
  if (!r.city || r.city === '省直辖县级行政区划') continue
  const lat = Number(r.lat), lng = Number(r.lng)
  if (!(lat >= 3 && lat <= 54 && lng >= 73 && lng <= 136)) continue
  // 市辖区（直辖市）按省级归并；其余按省|市
  const isMunicipality = r.city === '市辖区'
  const key = isMunicipality ? r.province : r.province + '|' + r.city
  if (byCity.has(key)) continue           // 只取第一条（市中心）
  byCity.set(key, {
    province: r.province,
    name: isMunicipality ? r.province.replace(/市$/, '') : r.city,
    lat, lng,
  })
}

