/** 由经纬度找最近的收录城市（等距圆柱近似，用于 GPS 就近定位） */
export function nearestCity(lat, lng) {
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null
  let best = null
  let bestD = Infinity
  for (const [name, province, la, ln, ancient] of CITIES) {
    const dx = (ln - lng) * Math.cos(((lat + la) / 2) * Math.PI / 180)
    const dy = la - lat
    const d = dx * dx + dy * dy
    if (d < bestD) { bestD = d; best = { name, province, lat: la, lng: ln, ancient: ancient || '' } }
  }
  return best
}

/** 按现代名或古称模糊搜索 */
export function searchCities(q) {
  const key = String(q || '').trim()
  if (!key) return CITIES.map(toCity)
  return CITIES.filter(([n, , , , a]) => n.includes(key) || (a && a.includes(key))).map(toCity)
}

