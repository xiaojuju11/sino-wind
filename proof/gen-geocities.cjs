// 关键：数据集里每个城市【第一条】即市中心（area 为空的那条），
// 用全部区县算术平均会把中心拉向远郊。实测两者对已知市中心的平均偏差：
//   算术平均 28.9km  vs  取第一条 5.0km  —— 故取第一条。
