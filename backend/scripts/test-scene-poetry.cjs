const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { encodeMask } = require('../src/utils/sceneMasks')
const root = path.resolve(__dirname, '../..')
const frontend = name => import(pathToFileURL(path.join(root, 'frontend/src', name)).href)

test('segmentation run encoding round trips across rows and preserves bounds', async () => {
  const { decodeRuns } = await frontend('utils/sceneImage.js')
  const pixels = Uint8Array.from([0,255,255,0,255,0,0,255,255,255,0,0])
  const mask = encodeMask(pixels, 4, 3, new Uint8Array(12).fill(128))
  assert.deepEqual([...decodeRuns(mask.runs, 12)], [...pixels].map(x => x ? 1 : 0))
  assert.equal(mask.area, .5)
  assert.deepEqual(mask.box, [0,0,1,1])
  assert.equal(mask.near, 128 / 255)
})
test('manual regions clamp reversed drags and reject accidental taps', async () => {
  const { manualRegion, decodeRuns } = await frontend('utils/sceneImage.js')
  const result = manualRegion({ x: 1.2, y: .8 }, { x: -.2, y: .2 }, 10, 10, 'tree', '树木')
  assert.equal(decodeRuns(result.runs, 100).reduce((a,b) => a+b,0), 60)
  assert.deepEqual(result.box,[0,.2,1,.8])
  assert.equal(manualRegion({x:.1,y:.1},{x:.11,y:.11},10,10,'tree','树木'),null)
})
test('poetry ranking uses confirmed motifs, never equates sky with stars or water with lotus', async () => {
  const { matchScenePoems, SCENE_POEMS, SCENE_TAGS } = await frontend('data/scenePoems.js')
  assert.deepEqual(matchScenePoems([]), [])
  assert.deepEqual(matchScenePoems(['unknown']), [])
  assert(!matchScenePoems(['sky']).some(p => p.id === 'libai-yelou'))
  assert(!matchScenePoems(['water']).some(p => p.id === 'hanyuefu-jiangnan'))
  assert(matchScenePoems(['water','mountain']).some(p => p.id === 'sushi-yuhou' && p.matched.length === 2))
  assert.equal(new Set(SCENE_POEMS.map(p=>p.id)).size, SCENE_POEMS.length)
  for (const p of SCENE_POEMS) for (const [word,tag] of p.anchors) { assert(p.lines.join('').includes(word)); assert(SCENE_TAGS[tag]) }
})
test('snow mountains, lakeside buildings and flower fields select fitting verse', async () => {
  const { matchScenePoems } = await frontend('data/scenePoems.js')
  const mountains = [{tag:'mountain',area:.62},{tag:'snow',area:.18},{tag:'tree',area:.04},{tag:'grass',area:.005},{tag:'sky',area:.3}]
  const snowy = matchScenePoems(mountains)
  assert.equal(snowy[0].id, 'zuyong-zhongnan')
  assert(!snowy.some(p => p.id === 'menghaoran-guren' || p.id === 'zhaoshixiu-youyue'))
  const park = matchScenePoems([{tag:'water',area:.42},{tag:'tree',area:.35},{tag:'building',area:.12},{tag:'grass',area:.04}])
  assert.equal(park[0].id, 'gaopian-shanting')
  assert(!park.some(p => p.id === 'zhaoshixiu-youyue'))
  const flowers = matchScenePoems([{tag:'flower',area:.55},{tag:'grass',area:.16},{tag:'sky',area:.3}])
  assert.equal(flowers[0].id, 'baijuyi-qiantang')
  assert(!flowers.some(p => p.id === 'wangwei-zhuli' || p.id === 'hanyuefu-jiangnan'))
})
test('large landscape subjects outrank tiny incidental grass and selections remain authoritative', async () => {
  const { matchScenePoems } = await frontend('data/scenePoems.js')
  const result = matchScenePoems([{tag:'mountain',area:.65},{tag:'grass',area:.005},{tag:'sky',area:.3}])
  assert.equal(result[0].id, 'libai-jingting')
  assert(result.find(p=>p.id==='baijuyi-fude').rank < result[0].rank)
  assert(!matchScenePoems(['tree','mountain']).some(p=>p.id==='menghaoran-guren'))
  assert(matchScenePoems(['tree','mountain','building']).some(p=>p.id==='menghaoran-guren'))
  assert(!matchScenePoems([{tag:'snow',area:0},{tag:'mountain',area:.6}]).some(p=>p.id==='zuyong-zhongnan'))
})
const api = process.env.SCENE_API
test('HTTP rejects malformed images and returns genuine mask/depth output', { skip: !api, timeout: 100000 }, async () => {
  const post = image => fetch(`${api}/analyze`, {method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({image})})
  assert.equal((await post('not-an-image')).status,400)
  assert.equal((await post('data:image/png;base64,YWJj')).status,400)
  const image = 'data:image/webp;base64,' + fs.readFileSync(path.join(root,'frontend/public/images/scene/poetic-lake-v1.webp')).toString('base64')
  const result = await post(image); assert.equal(result.status,200)
  const { data } = await result.json()
  assert(data.regions.length > 0)
  assert.equal(data.depth.length,data.width*data.height)
  for (const region of data.regions) {
    assert.equal(region.source,'model'); assert(region.area > 0 && region.area <= 1)
    for(let i=0;i<region.runs.length;i+=2) assert(region.runs[i]>=0 && region.runs[i]+region.runs[i+1]<=data.width*data.height)
  }
})
